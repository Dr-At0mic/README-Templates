// ADHD — the README itself. Visual Showcase archetype (github-profile-readme skill) with a
// persona accent: one cinematic hero, centred identity and links, then real substance — the
// signal panel with a plain-language key, and projects as open tabs. Every image is self-hosted
// and fully described; everything a recruiter or screen reader needs is real text.

import { adhdNumbers, defaultThought, heroSvg, signalSvg, slateSvg } from './art';

const ASSETS = {
  heroDark: 'assets/adhd-hero-dark.svg',
  heroLight: 'assets/adhd-hero-light.svg',
  signalDark: 'assets/adhd-signal-dark.svg',
  signalLight: 'assets/adhd-signal-light.svg',
  endDark: 'assets/adhd-end-dark.svg',
  endLight: 'assets/adhd-end-light.svg',
};

const DEFAULT_SIGNOFF = 'Thanks for your attention.';
const DEFAULT_POSTSCRIPT = 'I know it’s a limited resource.';

const html = (s) => String(s ?? '').replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;').replace(/"/g, '&quot;');

function picture(dark, light, alt) {
  return [
    '<p align="center">',
    '<picture>',
    `  <source media="(prefers-color-scheme: dark)" srcset="./${dark}">`,
    `  <img alt="${html(alt)}" src="./${light}" width="100%">`,
    '</picture>',
    '</p>',
  ].join('\n');
}

function links(p) {
  const twitter = p.twitter?.replace(/^@/, '');
  const items = [
    p.website && `<a href="${html(p.website)}">${html(p.website.replace(/^https?:\/\//, '').replace(/\/$/, ''))}</a>`,
    p.email && `<a href="mailto:${html(p.email)}">${html(p.email)}</a>`,
    twitter && `<a href="https://x.com/${html(twitter)}">X @${html(twitter)}</a>`,
    p.linkedin && `<a href="${html(p.linkedin)}">LinkedIn</a>`,
  ].filter(Boolean);
  return items.length ? `<p align="center">${items.join(' &nbsp;·&nbsp; ')}</p>` : '';
}

function options(p) {
  const o = p.templateData?.adhd || {};
  return {
    thought: o.thought?.trim() || defaultThought(p),
    signoff: o.signoff?.trim() || DEFAULT_SIGNOFF,
    postscript: o.postscript?.trim() || DEFAULT_POSTSCRIPT,
  };
}

export function render(p) {
  const opts = options(p);
  const name = p.name || p.login;
  const n = adhdNumbers(p);
  const featured = p.featured.map((r) => p.repos.find((x) => x.name === r)).filter(Boolean);
  const fmt = (v) => v.toLocaleString('en-US');
  const langs = (p.languages || []).slice(0, 5);
  const top = n.episodes[0];

  const out = [
    picture(
      ASSETS.heroDark,
      ASSETS.heroLight,
      `${name}: ${(p.headline || 'GitHub profile').replace(/[.!?\s]+$/, '')}. Cinematic title card: a camera's autofocus hunts through notifications, open tabs and a sticky note reading “${opts.thought}”, then locks onto the name.`
    ),
    '',
    `<p align="center"><b>${html(name)}</b>${p.headline ? ` · ${html(p.headline)}` : ''}</p>`,
    links(p),
    '',
  ];

  if (p.intro) out.push(`**In focus.** ${p.intro}`, '');
  if (p.now) out.push(`**Currently hyperfocused on:** ${p.now}`, '');

  out.push(
    '#### Signal',
    '',
    picture(
      ASSETS.signalDark,
      ASSETS.signalLight,
      `The last 365 days as a seismograph: ${fmt(n.total)} contributions on ${fmt(n.active)} active days` +
        (top ? `, biggest hyperfocus episode ${top.length} days and ${fmt(top.sum)} contributions` : '') +
        `. Longest streak ${n.streak} days, ${fmt(n.stars)} stars, ${fmt(n.followers)} followers, ${n.years} years on GitHub.` +
        (langs.length ? ` Languages: ${langs.map((l) => `${l.name} ${Math.round(l.share * 100)}%`).join(', ')}.` : '')
    ),
    '',
    '<details>',
    '<summary><sub>Reading the signal</sub></summary>',
    '',
    `- **Seismograph:** one swing of the pen per day of the last 365. The bigger the swing, the busier the day.` +
      (n.episodes.length
        ? ` Orange bands mark hyperfocus episodes, the most intense runs of back-to-back busy days. The biggest, HF-1, ran ${top.length} days and logged ${fmt(top.sum)} contributions.`
        : ''),
    `- **Time, as experienced:** there are two times, now and not now. The bars under the clock are contributions by weekday${n.peakDayName ? ` (busiest: ${n.peakDayName.charAt(0)}${n.peakDayName.slice(1).toLowerCase()})` : ''}.`,
    `- **Counters:** longest streak, contributions in the last 12 months, active days, stars, followers and years on GitHub.`,
    `- **Dopamine by source:** language share by bytes across public repositories.`,
    `- **The opening shot:** autofocus hunts through the noise, then locks on. The out-of-focus lights behind it are the last 12 months, one per month; bigger and brighter means busier.`,
    '',
    '<sub>ADHD isn’t a shortage of attention. Attention goes where interest is, and when it gets there it locks on hard. Artwork: original animated SVG, generated by README Templates · template: ADHD. Motion stops if your system asks for reduced motion.</sub>',
    '',
    '</details>',
    ''
  );

  if (featured.length) {
    out.push('#### Open tabs', '');
    featured.forEach((repo, i) => {
      out.push(`- \`TAB ${String(i + 1).padStart(2, '0')}\` **[${repo.name}](${repo.url})**${repo.description ? ` · ${repo.description}` : ''}  `);
      const meta = [repo.language, repo.stars ? `★ ${repo.stars >= 1000 ? `${(repo.stars / 1000).toFixed(1)}k` : repo.stars}` : '']
        .filter(Boolean)
        .join(' · ');
      if (meta) out.push(`  <sub>${meta}</sub>`);
    });
    out.push('');
  }

  out.push(picture(ASSETS.endDark, ASSETS.endLight, `A film slate snaps shut: that's a wrap. ${opts.signoff} ${opts.postscript}`));

  return {
    markdown: out.join('\n') + '\n',
    assets: {
      [ASSETS.heroDark]: heroSvg(p, 'dark', opts),
      [ASSETS.heroLight]: heroSvg(p, 'light', opts),
      [ASSETS.signalDark]: signalSvg(p, 'dark'),
      [ASSETS.signalLight]: signalSvg(p, 'light'),
      [ASSETS.endDark]: slateSvg(p, 'dark', opts),
      [ASSETS.endLight]: slateSvg(p, 'light', opts),
    },
  };
}

export const adhd = {
  id: 'adhd',
  name: 'ADHD',
  tagline: 'A cinema camera hunts for focus through a storm of notifications and open tabs, then locks onto your name. Your year as a seismograph of hyperfocus.',
  animated: true,
  tags: ['Animated', 'Cinematic', 'Neurodivergent'],
  hero: (p, theme) => heroSvg(p, theme, options(p)),
  fields: [
    {
      key: 'thought',
      label: 'Loudest thought',
      help: 'Scribbled on the sticky note in the opening shot.',
      maxLength: 52,
      placeholder: (p) => defaultThought(p),
    },
    {
      key: 'signoff',
      label: 'Closing line',
      help: 'The big line on the end card, next to the film slate.',
      maxLength: 32,
      placeholder: () => DEFAULT_SIGNOFF,
    },
    {
      key: 'postscript',
      label: 'Postscript',
      help: 'Typed out under the closing line.',
      maxLength: 56,
      placeholder: () => DEFAULT_POSTSCRIPT,
    },
  ],
  render,
};
