// Annual Report — the README itself. Descriptive Resume archetype (github-profile-readme skill) with a
// Visual Showcase accent: a report cover, then the substance a recruiter or board reads first — name and
// role as text, a letter, highlights, key figures with notes, and the portfolio of projects.

import { closingSvg, figuresSvg, heroSvg } from './art';
import { renderLinks } from '../../lib/links';
import { renderSponsorWall } from '../../lib/sponsors';
import { featuredRepos, fmt, formatDate, html, languageText, picture, proNumbers, repoList, roleLine, splitList } from '../common';

const ASSETS = {
  heroDark: 'assets/annual-cover-dark.svg',
  heroLight: 'assets/annual-cover-light.svg',
  figuresDark: 'assets/annual-figures-dark.svg',
  figuresLight: 'assets/annual-figures-light.svg',
  endDark: 'assets/annual-closing-dark.svg',
  endLight: 'assets/annual-closing-light.svg',
};

const DEFAULT_SIGNOFF = 'Thank you for reading.';

function options(p) {
  const o = p.templateData?.annual || {};
  return {
    title: o.title?.trim() || '',
    organisation: o.organisation?.trim() || '',
    highlights: splitList(o.highlights),
    signoff: o.signoff?.trim() || DEFAULT_SIGNOFF,
  };
}

const coverAlt = (p, opts) => {
  const n = proNumbers(p);
  const role = roleLine(opts.title, opts.organisation);
  return `${p.name || p.login}${role ? `, ${role}` : ''}: ${(p.headline || 'GitHub profile').replace(/[.!?\s]+$/, '')}. Annual report cover with ${fmt(n.total)} contributions, ${fmt(n.active)} active days, ${fmt(n.stars)} stars and ${fmt(n.followers)} followers, and a bar chart of contributions per month.`;
};

const figuresAlt = (p) => {
  const n = proNumbers(p);
  return `Key figures for the last twelve months: ${fmt(n.total)} contributions on ${fmt(n.active)} active days, ${n.perActive.toFixed(1)} per active day, longest streak ${n.streak} days${
    n.best ? `, busiest day ${formatDate(n.best.date)} with ${fmt(n.best.count)}` : ''
  }, ${fmt(n.stars)} stars, ${fmt(n.followers)} followers, on GitHub since ${n.since}.${n.languages.length ? ` Languages: ${languageText(n.languages)}.` : ''}`;
};

export function render(p) {
  const contact = renderLinks(p, { align: 'left' });
  const wall = renderSponsorWall(p, { align: 'left' });
  const opts = options(p);
  const name = p.name || p.login;
  const role = roleLine(opts.title, opts.organisation);
  const featured = featuredRepos(p);

  const out = [picture(ASSETS.heroDark, ASSETS.heroLight, coverAlt(p, opts)), ''];
  out.push(`**${html(name)}**${role ? ` · ${html(role)}` : ''}  `);
  if (p.headline) out.push(html(p.headline));
  out.push('');
  if (contact.html) out.push(contact.html, '');

  if (p.intro) out.push(`**Letter to readers.** ${p.intro}`, '');
  if (p.now) out.push(`**Outlook.** ${p.now}`, '');

  if (opts.highlights.length) {
    out.push('#### Highlights', '');
    for (const item of opts.highlights) out.push(`- ${item}`);
    out.push('');
  }

  out.push(
    '#### Key figures',
    '',
    picture(ASSETS.figuresDark, ASSETS.figuresLight, figuresAlt(p)),
    '',
    '<details>',
    '<summary><sub>Notes to the figures</sub></summary>',
    '',
    '- **Period:** the last twelve months of public GitHub activity, as GitHub counts contributions (commits, pull requests, issues and reviews).',
    '- **Cover chart:** contributions per calendar month. The brass bar is the busiest month, and the dotted line is the monthly average. The percentage compares the second half of the year with the first.',
    '- **Stars** are summed across public, non-fork repositories. **Portfolio** is language share by bytes across the same repositories.',
    '',
    '<sub>Artwork: original animated SVG, generated by README Templates · template: Annual Report. Motion stops if your system asks for reduced motion.</sub>',
    '',
    '</details>',
    ''
  );

  if (featured.length) out.push('#### Portfolio', '', ...repoList(featured, () => '', ' — '), '');
  if (wall.html) out.push(wall.html, '');
  out.push(picture(ASSETS.endDark, ASSETS.endLight, `Closing note: ${opts.signoff} ${name}${role ? `, ${role}` : ''}.`));

  return {
    markdown: out.join('\n') + '\n',
    assets: {
      ...contact.assets,
      ...wall.assets,
      [ASSETS.heroDark]: heroSvg(p, 'dark', opts),
      [ASSETS.heroLight]: heroSvg(p, 'light', opts),
      [ASSETS.figuresDark]: figuresSvg(p, 'dark'),
      [ASSETS.figuresLight]: figuresSvg(p, 'light'),
      [ASSETS.endDark]: closingSvg(p, 'dark', opts),
      [ASSETS.endLight]: closingSvg(p, 'light', opts),
    },
  };
}

export const annual = {
  id: 'annual',
  name: 'Annual Report',
  tagline: 'Your year as a shareholder report: a serif cover, key figures that roll into place like an odometer, and twelve months of work as an audited chart.',
  animated: true,
  tags: ['Animated', 'Professional', 'Editorial'],
  hero: (p, theme) => heroSvg(p, theme, options(p)),
  fields: [
    { key: 'title', label: 'Title', help: 'Your role, in brass capitals above your name. Leave empty to hide.', maxLength: 40, placeholder: () => 'Founder & CEO' },
    { key: 'organisation', label: 'Organisation', help: 'Shown after your title.', maxLength: 40, placeholder: () => 'Company or team' },
    {
      key: 'highlights',
      label: 'Highlights',
      help: 'Up to three achievements, separated by semicolons. Listed as text under your letter.',
      maxLength: 240,
      placeholder: () => 'Shipped v2 to 40 teams; Grew the team to 12; Spoke at a conference',
    },
    { key: 'signoff', label: 'Closing line', help: 'Set in italics above your name at the end.', maxLength: 48, placeholder: () => DEFAULT_SIGNOFF },
  ],
  sponsorPage: {
    align: 'left',
    defaults: { signoff: 'With thanks to every backer.' },
    pitchLabel: 'Letter to backers.',
    nowLabel: 'Outlook.',
    role: (p) => roleLine(options(p).title, options(p).organisation),
    heroAlt: (p) => coverAlt(p, options(p)),
    panel: { title: 'Key figures', art: (p) => figuresSvg(p, 'dark'), alt: figuresAlt },
    fundsTitle: 'The portfolio your sponsorship supports',
    wall: { heading: 'Our backers', top: 'Principal backers', regular: 'Backers', oneTime: 'Contributors' },
    outro: 'Every figure above was earned in public. Sponsorship funds the next report.',
    end: {
      art: (p) => closingSvg(p, 'dark', options(p)),
      alt: (p) => `Closing note: ${options(p).signoff} ${p.name || p.login}.`,
    },
  },
  render,
};
