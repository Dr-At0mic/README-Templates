// Departures — the README itself. Visual Showcase archetype (github-profile-readme skill): one board as
// the hero, then name, role and intro as real text, the timetable with a key, and the departures
// (projects) as a plain list with their flight numbers.

import { finalCallSvg, flightNumber, heroSvg, timetableSvg } from './art';
import { renderLinks } from '../../lib/links';
import { renderSponsorWall } from '../../lib/sponsors';
import { featuredRepos, fmt, html, picture, proNumbers, repoList, roleLine } from '../common';

const ASSETS = {
  heroDark: 'assets/departures-board-dark.svg',
  heroLight: 'assets/departures-board-light.svg',
  tableDark: 'assets/departures-timetable-dark.svg',
  tableLight: 'assets/departures-timetable-light.svg',
  endDark: 'assets/departures-final-dark.svg',
  endLight: 'assets/departures-final-light.svg',
};

const DEFAULT_SIGNOFF = 'Thanks for stopping by';
const DAYS = ['Sunday', 'Monday', 'Tuesday', 'Wednesday', 'Thursday', 'Friday', 'Saturday'];

function options(p) {
  const o = p.templateData?.departures || {};
  return {
    title: o.title?.trim() || '',
    organisation: o.organisation?.trim() || '',
    signoff: o.signoff?.trim() || DEFAULT_SIGNOFF,
  };
}

const heroAlt = (p, opts) => {
  const role = roleLine(opts.title, opts.organisation);
  const repos = featuredRepos(p);
  return `${p.name || p.login}${role ? `, ${role}` : ''}: ${(p.headline || 'GitHub profile').replace(/[.!?\s]+$/, '')}. A split-flap departures board that clatters into place, spelling the name${
    repos.length ? ` and listing departures to ${repos.map((r) => r.name).join(', ')}` : ''
  }.${p.now ? ` Now boarding: ${p.now}` : ''}`;
};

const tableAlt = (p) => {
  const n = proNumbers(p);
  const busiest = n.weekdayAvg.indexOf(Math.max(...n.weekdayAvg));
  return `Timetable: average contributions per weekday over the last year, busiest on ${DAYS[busiest]}s (${n.weekdayAvg[busiest].toFixed(1)} a day). ${fmt(n.total)} contributions, ${fmt(n.active)} active days, longest streak ${n.streak} days, ${fmt(n.stars)} stars, ${fmt(n.followers)} followers, on GitHub since ${n.since}.`;
};

export function render(p) {
  const contact = renderLinks(p);
  const wall = renderSponsorWall(p);
  const opts = options(p);
  const name = p.name || p.login;
  const role = roleLine(opts.title, opts.organisation);
  const featured = featuredRepos(p);

  const out = [
    picture(ASSETS.heroDark, ASSETS.heroLight, heroAlt(p, opts)),
    '',
    `<p align="center"><b>${html(name)}</b>${role ? ` · ${html(role)}` : ''}${p.headline ? `<br>${html(p.headline)}` : ''}</p>`,
    contact.html,
    '',
  ];

  if (p.intro) out.push(`**Itinerary.** ${p.intro}`, '');
  if (p.now) out.push(`**Now boarding:** ${p.now}`, '');

  out.push(
    '#### Timetable',
    '',
    picture(ASSETS.tableDark, ASSETS.tableLight, tableAlt(p)),
    '',
    '<details>',
    '<summary><sub>Reading the board</sub></summary>',
    '',
    '- **Departures** are featured repositories. Flight numbers come from your initials, **via** is the main language, and **stars** are the stars.',
    '- **Now boarding** is what you are working on now.',
    '- **The timetable** is the average number of contributions on each day of the week over the last twelve months; the amber row is the busiest day. On the right is the year in numbers.',
    '',
    '<sub>Artwork: original animated SVG, generated by README Templates · template: Departures. Motion stops if your system asks for reduced motion.</sub>',
    '',
    '</details>',
    ''
  );

  if (featured.length) out.push('#### Departures', '', ...repoList(featured, (i) => `\`${flightNumber(p, i)}\` `), '');
  if (wall.html) out.push(wall.html, '');
  out.push(picture(ASSETS.endDark, ASSETS.endLight, `Final call: ${opts.signoff}.`));

  return {
    markdown: out.join('\n') + '\n',
    assets: {
      ...contact.assets,
      ...wall.assets,
      [ASSETS.heroDark]: heroSvg(p, 'dark', opts),
      [ASSETS.heroLight]: heroSvg(p, 'light', opts),
      [ASSETS.tableDark]: timetableSvg(p, 'dark'),
      [ASSETS.tableLight]: timetableSvg(p, 'light'),
      [ASSETS.endDark]: finalCallSvg(p, 'dark', opts),
      [ASSETS.endLight]: finalCallSvg(p, 'light', opts),
    },
  };
}

export const departures = {
  id: 'departures',
  name: 'Departures',
  tagline: 'A split-flap departures board: your name clatters into place letter by letter, your projects are the flights, and what you’re on now is boarding.',
  animated: true,
  tags: ['Animated', 'Professional', 'Mechanical'],
  hero: (p, theme) => heroSvg(p, theme, options(p)),
  fields: [
    { key: 'title', label: 'Title', help: 'Flipped in on the row under your name. Defaults to the first sentence of your headline.', maxLength: 40, placeholder: () => 'Principal Consultant' },
    { key: 'organisation', label: 'Organisation', help: 'Shown after your title.', maxLength: 40, placeholder: () => 'Company or team' },
    { key: 'signoff', label: 'Final call', help: 'Flipped in on the last board.', maxLength: 40, placeholder: () => DEFAULT_SIGNOFF },
  ],
  sponsorPage: {
    defaults: { signoff: 'Thank you for flying with us' },
    pitchLabel: 'Flight plan.',
    nowLabel: 'Now boarding:',
    role: (p) => roleLine(options(p).title, options(p).organisation),
    heroAlt: (p) => heroAlt(p, options(p)),
    panel: { title: 'Timetable', art: (p) => timetableSvg(p, 'dark'), alt: tableAlt },
    fundsTitle: 'Routes your sponsorship keeps flying',
    repoPrefix: (i) => `\`GATE ${i + 1}\` `,
    wall: { heading: 'Passenger list', top: 'First class', regular: 'Frequent flyers', oneTime: 'Passengers' },
    outro: 'Every sponsor keeps another route on the board.',
    end: { art: (p) => finalCallSvg(p, 'dark', options(p)), alt: (p) => `Final call: ${options(p).signoff}.` },
  },
  render,
};
