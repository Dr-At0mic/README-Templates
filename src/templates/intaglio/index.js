// Intaglio — the README itself. Minimalist / Prose-First archetype (github-profile-readme skill) with a
// Visual Showcase accent: one engraved certificate, then name, role and a short statement in real text,
// the coupon sheet with a key, and the holdings (projects) as a plain list.

import { counterfoilSvg, couponsSvg, heroSvg, serialNumber } from './art';
import { renderLinks } from '../../lib/links';
import { renderSponsorWall } from '../../lib/sponsors';
import { featuredRepos, fmt, html, initials, languageText, picture, proNumbers, repoList, roleLine } from '../common';

const ASSETS = {
  heroDark: 'assets/intaglio-certificate-dark.svg',
  heroLight: 'assets/intaglio-certificate-light.svg',
  couponsDark: 'assets/intaglio-coupons-dark.svg',
  couponsLight: 'assets/intaglio-coupons-light.svg',
  endDark: 'assets/intaglio-counterfoil-dark.svg',
  endLight: 'assets/intaglio-counterfoil-light.svg',
};

const DEFAULT_HEADING = 'Certificate of Standing';
const DEFAULT_SIGNOFF = 'Redeemable for one good conversation';

function options(p) {
  const o = p.templateData?.intaglio || {};
  return {
    title: o.title?.trim() || '',
    organisation: o.organisation?.trim() || '',
    heading: o.heading?.trim() || DEFAULT_HEADING,
    signoff: o.signoff?.trim() || DEFAULT_SIGNOFF,
  };
}

const heroAlt = (p, opts) => {
  const n = proNumbers(p);
  const role = roleLine(opts.title, opts.organisation);
  return `${p.name || p.login}${role ? `, ${role}` : ''}: ${(p.headline || 'GitHub profile').replace(/[.!?\s]+$/, '')}. An engraved ${opts.heading.toLowerCase()} No. ${serialNumber(p)}, certifying ${fmt(n.total)} contributions on ${fmt(n.active)} days of the past year and an account held since ${n.since}, with a guilloché medallion around the monogram ${initials(p.name || p.login)} and a vermilion seal.`;
};

const couponsAlt = (p) => {
  const n = proNumbers(p);
  return `The last twelve months as a sheet of bond coupons, contributions per month: ${n.months.map((m) => `${m.label} ${fmt(m.total)}`).join(', ')}.${
    n.languages.length ? ` Denominations (languages): ${languageText(n.languages)}.` : ''
  }`;
};

export function render(p) {
  const contact = renderLinks(p);
  const wall = renderSponsorWall(p);
  const opts = options(p);
  const name = p.name || p.login;
  const role = roleLine(opts.title, opts.organisation);
  const featured = featuredRepos(p);

  const out = [
    picture(ASSETS.heroDark, ASSETS.heroLight, heroAlt(p, opts)),
    '',
    `<p align="center"><b>${html(name)}</b>${role ? `<br><i>${html(role)}</i>` : ''}${p.headline ? `<br>${html(p.headline)}` : ''}</p>`,
    contact.html,
    '',
  ];

  if (p.intro) out.push(`**Statement.** ${p.intro}`, '');
  if (p.now) out.push(`**Current undertaking.** ${p.now}`, '');

  out.push(
    '#### Schedule of coupons',
    '',
    picture(ASSETS.couponsDark, ASSETS.couponsLight, couponsAlt(p)),
    '',
    '<details>',
    '<summary><sub>Reading the certificate</sub></summary>',
    '',
    '- **The medallion** is guilloché, the fine-line engraving used on banknotes and share certificates. Its outer ring is drawn from your year: twelve months clockwise from the top, swelling outward in the busier ones.',
    '- **The citation** is the last twelve months of public contributions, the days you contributed, your longest streak, and the year you joined GitHub.',
    `- **The serial number** is your initials, the year you joined and your contributions this year: ${serialNumber(p)}.`,
    '- **Coupons** are calendar months. The stamped one was the busiest. **Denominations** are language share by bytes across public repositories.',
    '',
    '<sub>Artwork: original animated SVG, generated by README Templates · template: Intaglio. Motion stops if your system asks for reduced motion.</sub>',
    '',
    '</details>',
    ''
  );

  if (featured.length) out.push('#### Holdings', '', ...repoList(featured), '');
  if (wall.html) out.push(wall.html, '');
  out.push(picture(ASSETS.endDark, ASSETS.endLight, `Counterfoil No. ${serialNumber(p)}. ${opts.signoff}. Sealed by ${name}.`));

  return {
    markdown: out.join('\n') + '\n',
    assets: {
      ...contact.assets,
      ...wall.assets,
      [ASSETS.heroDark]: heroSvg(p, 'dark', opts),
      [ASSETS.heroLight]: heroSvg(p, 'light', opts),
      [ASSETS.couponsDark]: couponsSvg(p, 'dark'),
      [ASSETS.couponsLight]: couponsSvg(p, 'light'),
      [ASSETS.endDark]: counterfoilSvg(p, 'dark', opts),
      [ASSETS.endLight]: counterfoilSvg(p, 'light', opts),
    },
  };
}

export const intaglio = {
  id: 'intaglio',
  name: 'Intaglio',
  tagline: 'An engraved certificate in the manner of a banknote: a guilloché medallion spun from your year, your name in hatched capitals, and a seal that stamps down.',
  animated: true,
  tags: ['Animated', 'Professional', 'Engraved'],
  hero: (p, theme) => heroSvg(p, theme, options(p)),
  fields: [
    { key: 'title', label: 'Title', help: 'Set in italics under your name on the certificate.', maxLength: 40, placeholder: () => 'Managing Partner' },
    { key: 'organisation', label: 'Organisation', help: 'Shown after your title.', maxLength: 40, placeholder: () => 'Company or firm' },
    { key: 'heading', label: 'Certificate title', help: 'Engraved across the top.', maxLength: 32, placeholder: () => DEFAULT_HEADING },
    { key: 'signoff', label: 'Counterfoil line', help: 'Engraved in capitals on the counterfoil at the end.', maxLength: 44, placeholder: () => DEFAULT_SIGNOFF },
  ],
  sponsorPage: {
    defaults: { heading: 'Certificate of Patronage', signoff: 'With gratitude to every patron' },
    pitchLabel: 'Statement to patrons.',
    nowLabel: 'Current undertaking.',
    role: (p) => roleLine(options(p).title, options(p).organisation),
    heroAlt: (p) => heroAlt(p, options(p)),
    panel: { title: 'Schedule of coupons', art: (p) => couponsSvg(p, 'dark'), alt: couponsAlt },
    fundsTitle: 'Holdings your patronage underwrites',
    wall: { heading: 'Register of patrons', top: 'Founding patrons', regular: 'Patrons', oneTime: 'Benefactors' },
    outro: 'Every patron is entered in the register. Thank you for underwriting the work.',
    end: { art: (p) => counterfoilSvg(p, 'dark', options(p)), alt: (p) => `Counterfoil No. ${serialNumber(p)}. ${options(p).signoff}.` },
  },
  render,
};
