// Singularity — the README itself. Visual Showcase archetype (github-profile-readme skill):
// one centred cinematic hero, centred identity and links, then real substance — a mission brief,
// telemetry, and a flight log of projects — with every image self-hosted and fully described.

import { heroSvg, missionNumbers, roman, telemetrySvg, transmissionEndSvg } from './art';

const ASSETS = {
  heroDark: 'assets/singularity-hero-dark.svg',
  heroLight: 'assets/singularity-hero-light.svg',
  telemetryDark: 'assets/singularity-telemetry-dark.svg',
  telemetryLight: 'assets/singularity-telemetry-light.svg',
  endDark: 'assets/singularity-end-dark.svg',
  endLight: 'assets/singularity-end-light.svg',
};

const html = (s) => String(s ?? '').replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;').replace(/"/g, '&quot;');

function picture(dark, light, alt) {
  return [
    '<p align="center">',
    '<picture>',
    `  <source media="(prefers-color-scheme: dark)" srcset="./${dark}">`,
    `  <img alt="${html(alt)}" src="./${light}" width="100%">`,
    '</picture>',
    '</p>',
  ].join('\n');
}

function links(p) {
  const twitter = p.twitter?.replace(/^@/, '');
  const items = [
    p.website && `<a href="${html(p.website)}">${html(p.website.replace(/^https?:\/\//, '').replace(/\/$/, ''))}</a>`,
    p.email && `<a href="mailto:${html(p.email)}">${html(p.email)}</a>`,
    twitter && `<a href="https://x.com/${html(twitter)}">X @${html(twitter)}</a>`,
    p.linkedin && `<a href="${html(p.linkedin)}">LinkedIn</a>`,
  ].filter(Boolean);
  return items.length ? `<p align="center">${items.join(' &nbsp;·&nbsp; ')}</p>` : '';
}

export function defaultMissionName(p) {
  return `Horizon ${roman(missionNumbers(p).years)}`;
}

function options(p) {
  const o = p.templateData?.singularity || {};
  return {
    missionName: o.missionName?.trim() || defaultMissionName(p),
    signoff: o.signoff?.trim() || 'See you on the other side',
  };
}

export function render(p) {
  const opts = options(p);
  const name = p.name || p.login;
  const n = missionNumbers(p);
  const featured = p.featured.map((r) => p.repos.find((x) => x.name === r)).filter(Boolean);
  const fmt = (v) => v.toLocaleString('en-US');

  const out = [
    picture(
      ASSETS.heroDark,
      ASSETS.heroLight,
      `${name}: ${(p.headline || 'GitHub profile').replace(/[.!?\s]+$/, '')}. Cinematic title card: a black hole whose accretion disk is drawn from ${fmt(n.total)} contributions, one particle per day.`
    ),
    '',
    `<p align="center"><b>${html(name)}</b>${p.headline ? ` · ${html(p.headline)}` : ''}</p>`,
    links(p),
    '',
  ];

  if (p.intro || p.now) {
    if (p.intro) out.push(`> **Mission brief.** ${p.intro}`);
    if (p.intro && p.now) out.push('>');
    if (p.now) out.push(`> **Current objective.** ${p.now}`);
    out.push('');
  }

  out.push(
    '#### Telemetry',
    '',
    picture(
      ASSETS.telemetryDark,
      ASSETS.telemetryLight,
      `Mission telemetry for ${opts.missionName}: ${n.years} years on GitHub, ${fmt(n.total)} contributions in the last 12 months, ${fmt(n.active)} active days, longest streak ${n.streak} days, ${fmt(n.stars)} stars, ${fmt(n.followers)} followers.`
    ),
    '',
    '<details>',
    '<summary><sub>Reading the instruments</sub></summary>',
    '',
    `- **Accretion disk:** one particle per day of the last year; brighter and closer to the hole means a busier day. Inner rings orbit faster, as they would around a real black hole.`,
    `- **Orbit:** contributions per month, plotted as a closed trajectory; the beacon marks the busiest month.`,
    `- **Spectral composition:** language share by bytes across public repositories.`,
    `- **Light theme:** rendered as a photographic negative, the way astronomical survey plates were printed.`,
    '',
    `<sub>Artwork: original animated SVG, generated by README Templates · template: Singularity. Motion stops if your system asks for reduced motion.</sub>`,
    '',
    '</details>',
    ''
  );

  if (featured.length) {
    out.push('#### Flight log', '');
    featured.forEach((repo, i) => {
      out.push(`- \`MSN-${String(i + 1).padStart(2, '0')}\` **[${repo.name}](${repo.url})**${repo.description ? ` · ${repo.description}` : ''}  `);
      const meta = [repo.language, repo.stars ? `★ ${repo.stars >= 1000 ? `${(repo.stars / 1000).toFixed(1)}k` : repo.stars}` : '']
        .filter(Boolean)
        .join(' · ');
      if (meta) out.push(`  <sub>${meta}</sub>`);
    });
    out.push('');
  }

  out.push(picture(ASSETS.endDark, ASSETS.endLight, `End of transmission. ${opts.signoff}.`));

  return {
    markdown: out.join('\n') + '\n',
    assets: {
      [ASSETS.heroDark]: heroSvg(p, 'dark', opts),
      [ASSETS.heroLight]: heroSvg(p, 'light', opts),
      [ASSETS.telemetryDark]: telemetrySvg(p, 'dark', opts),
      [ASSETS.telemetryLight]: telemetrySvg(p, 'light', opts),
      [ASSETS.endDark]: transmissionEndSvg(p, 'dark', opts),
      [ASSETS.endLight]: transmissionEndSvg(p, 'light', opts),
    },
  };
}

export const singularity = {
  id: 'singularity',
  name: 'Singularity',
  tagline: 'A cinematic mission briefing: a black hole whose accretion disk is built from your contributions, one particle per day.',
  animated: true,
  tags: ['Animated', 'Cinematic', 'Sci-fi'],
  hero: (p, theme) => heroSvg(p, theme, options(p)),
  fields: [
    {
      key: 'missionName',
      label: 'Mission name',
      help: 'Shown in the letterbox and telemetry. Defaults to Horizon + your years on GitHub in Roman numerals.',
      maxLength: 28,
      placeholder: (p) => defaultMissionName(p),
    },
    {
      key: 'signoff',
      label: 'Sign-off',
      help: 'The last line, under "End of transmission".',
      maxLength: 48,
      placeholder: () => 'See you on the other side',
    },
  ],
  render,
};
