// Pulsar — the README itself.
// Follows the github-profile-readme skill's rules: identity in real text within the first lines,
// one coherent style, self-hosted images with dark/light variants and alt text, a clear contact path.

import { headerSvg, strataSvg } from './art';

const ASSETS = {
  headerDark: 'assets/pulsar-header-dark.svg',
  headerLight: 'assets/pulsar-header-light.svg',
  strataDark: 'assets/pulsar-strata-dark.svg',
  strataLight: 'assets/pulsar-strata-light.svg',
};

function picture(dark, light, alt) {
  // Wrapped in <p> so GitHub gives the artwork normal paragraph spacing.
  return [
    '<p>',
    '<picture>',
    `  <source media="(prefers-color-scheme: dark)" srcset="./${dark}">`,
    `  <img alt="${alt.replace(/"/g, '&quot;')}" src="./${light}" width="100%">`,
    '</picture>',
    '</p>',
  ].join('\n');
}

function formatStars(n) {
  return n >= 1000 ? `${(n / 1000).toFixed(n >= 10000 ? 0 : 1)}k` : String(n);
}

function contactLinks(p) {
  const twitter = p.twitter?.replace(/^@/, '');
  return [
    p.website && `[${p.website.replace(/^https?:\/\//, '').replace(/\/$/, '')}](${p.website})`,
    p.email && `[${p.email}](mailto:${p.email})`,
    twitter && `[X @${twitter}](https://x.com/${twitter})`,
    p.linkedin && `[LinkedIn](${p.linkedin})`,
  ].filter(Boolean);
}

export function render(p) {
  const name = p.name || p.login;
  const months = 12;
  const total = (p.contributions?.total || 0).toLocaleString('en-US');
  const featured = p.featured.map((n) => p.repos.find((r) => r.name === n)).filter(Boolean);
  const languages = (p.languages || []).slice(0, 5);
  const links = contactLinks(p);

  const out = [];
  out.push(
    picture(
      ASSETS.headerDark,
      ASSETS.headerLight,
      `${name} — ${(p.headline || 'GitHub profile').replace(/[.!?\s]+$/, '')}. Ridgeline of ${total} contributions over the last ${months} months, one ridge per month.`
    ),
    ''
  );

  // Identity as real text too — the header image is invisible to search and screen readers.
  out.push(p.headline ? `**${name}** — ${p.headline}` : `**${name}**`, '');
  if (p.intro) out.push(p.intro, '');
  if (p.now) out.push(`**Now** — ${p.now}`, '');
  if (links.length) out.push(links.join(' &nbsp;·&nbsp; '), '');

  if (featured.length) {
    out.push('#### Selected work', '');
    for (const repo of featured) {
      out.push(`- **[${repo.name}](${repo.url})**${repo.description ? ` — ${repo.description}` : ''}  `);
      const meta = [repo.language, repo.stars ? `★ ${formatStars(repo.stars)}` : ''].filter(Boolean).join(' · ');
      if (meta) out.push(`  <sub>${meta}</sub>`);
    }
    out.push('');
  }

  if (languages.length) {
    out.push('#### Stack', '');
    out.push(
      picture(
        ASSETS.strataDark,
        ASSETS.strataLight,
        `Language mix drawn as strata: ${languages.map((l) => `${l.name} ${Math.round(l.share * 100)}%`).join(', ')}.`
      ),
      ''
    );
  }

  out.push(
    '<details>',
    '<summary><sub>Colophon</sub></summary>',
    '',
    `<sub>The header is a ridgeline in the manner of the PSR B1919+21 pulsar plot: each line is one month, its shape traced from that month's daily contributions; the brightest line is the busiest month. Strata show language share by bytes across public repositories. Static SVG, generated by README Templates · template: Pulsar.</sub>`,
    '',
    '</details>'
  );

  const markdown = out.join('\n') + '\n';
  const assets = {
    [ASSETS.headerDark]: headerSvg(p, 'dark'),
    [ASSETS.headerLight]: headerSvg(p, 'light'),
  };
  if (languages.length) {
    assets[ASSETS.strataDark] = strataSvg(p, 'dark');
    assets[ASSETS.strataLight] = strataSvg(p, 'light');
  }
  return { markdown, assets };
}

export const pulsar = {
  id: 'pulsar',
  name: 'Pulsar',
  tagline: 'Your year as a ridgeline — one line per month, traced from real contributions.',
  tags: ['Static', 'Minimal', 'Data art'],
  hero: (p, theme) => headerSvg(p, theme),
  render,
};
