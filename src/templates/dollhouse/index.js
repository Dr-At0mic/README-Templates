// Dollhouse — the README itself. Persona/Themed archetype (github-profile-readme skill), kawaii
// variant: hero art → plain-text identity → "Dear diary" intro → stat-block as a diary page →
// favourite things (projects) → sign-off. All the sweetness lives in the images; everything a
// recruiter or screen reader needs is real text.

import { braceletSvg, defaultCatName, diarySvg, dollhouseNumbers, heroSvg } from './art';

const ASSETS = {
  heroDark: 'assets/dollhouse-hero-dark.svg',
  heroLight: 'assets/dollhouse-hero-light.svg',
  diaryDark: 'assets/dollhouse-diary-dark.svg',
  diaryLight: 'assets/dollhouse-diary-light.svg',
  endDark: 'assets/dollhouse-end-dark.svg',
  endLight: 'assets/dollhouse-end-light.svg',
};

const html = (s) => String(s ?? '').replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;').replace(/"/g, '&quot;');

function picture(dark, light, alt) {
  return [
    '<p align="center">',
    '<picture>',
    `  <source media="(prefers-color-scheme: dark)" srcset="./${dark}">`,
    `  <img alt="${html(alt)}" src="./${light}" width="100%">`,
    '</picture>',
    '</p>',
  ].join('\n');
}

function links(p) {
  const twitter = p.twitter?.replace(/^@/, '');
  const items = [
    p.website && `<a href="${html(p.website)}">${html(p.website.replace(/^https?:\/\//, '').replace(/\/$/, ''))}</a>`,
    p.email && `<a href="mailto:${html(p.email)}">${html(p.email)}</a>`,
    twitter && `<a href="https://x.com/${html(twitter)}">X @${html(twitter)}</a>`,
    p.linkedin && `<a href="${html(p.linkedin)}">LinkedIn</a>`,
  ].filter(Boolean);
  return items.length ? `<p align="center">${items.join(' &nbsp;·&nbsp; ')}</p>` : '';
}

function options(p) {
  const o = p.templateData?.dollhouse || {};
  return {
    speech: o.speech?.trim() || p.headline || 'Welcome to my dollhouse!',
    catName: o.catName?.trim() || defaultCatName(p),
    signoff: o.signoff?.trim() || 'XOXO',
  };
}

export function render(p) {
  const opts = options(p);
  const name = p.name || p.login;
  const n = dollhouseNumbers(p);
  const featured = p.featured.map((r) => p.repos.find((x) => x.name === r)).filter(Boolean);
  const fmt = (v) => v.toLocaleString('en-US');
  const langs = (p.languages || []).slice(0, 5);

  const out = [
    picture(
      ASSETS.heroDark,
      ASSETS.heroLight,
      `${name}: ${(p.headline || 'GitHub profile').replace(/[.!?\s]+$/, '')}. A pastel doll's-house room: a doll on heart balloons, a cat in heart-shaped sunglasses, and a kitten in a gift box${opts.speech !== p.headline ? ` saying “${opts.speech}”` : ''}.`
    ),
    '',
    `<p align="center"><b>${html(name)}</b>${p.headline ? ` · ${html(p.headline)}` : ''}</p>`,
    links(p),
    '',
  ];

  if (p.intro) out.push(`**Dear diary,** ${p.intro}`, '');
  if (p.now) out.push(`**Currently obsessed with:** ${p.now}`, '');

  out.push(
    '#### My diary',
    '',
    picture(
      ASSETS.diaryDark,
      ASSETS.diaryLight,
      `Diary page: the last year as a heart made of one tiny heart per day. Stickers: ${fmt(n.total)} contributions, ${n.streak}-day longest streak, ${fmt(n.followers)} followers, ${fmt(n.stars)} stars.` +
        (langs.length ? ` Favourite shades: ${langs.map((l) => `${l.name} ${Math.round(l.share * 100)}%`).join(', ')}.` : '')
    ),
    '',
    '<details>',
    '<summary><sub>How to read my diary</sub></summary>',
    '',
    `- **The heart:** one tiny heart per day of the last year, oldest on the left. Deeper pink means a busier day.`,
    `- **Stickers:** ${fmt(n.total)} contributions in the last 12 months, a ${n.streak}-day longest streak, a fan club of ${fmt(n.followers)} followers, and ${fmt(n.stars)} stars.`,
    `- **Nail polish:** top languages by share of code across public repositories; the fullest bottle is the favourite.`,
    `- **Fairy lights** (up top): one heart bulb per week; brighter means busier.`,
    `- **${opts.catName}:** the resident cat. Walks across everything. Not a metric.`,
    '',
    '<sub>Artwork: original animated SVG, generated by README Templates · template: Dollhouse. Motion stops if your system asks for reduced motion.</sub>',
    '',
    '</details>',
    ''
  );

  if (featured.length) {
    out.push('#### Favourite things', '');
    featured.forEach((repo) => {
      out.push(`- 🎀 **[${repo.name}](${repo.url})**${repo.description ? ` · ${repo.description}` : ''}  `);
      const meta = [repo.language, repo.stars ? `★ ${repo.stars >= 1000 ? `${(repo.stars / 1000).toFixed(1)}k` : repo.stars}` : '']
        .filter(Boolean)
        .join(' · ');
      if (meta) out.push(`  <sub>${meta}</sub>`);
    });
    out.push('');
  }

  out.push(picture(ASSETS.endDark, ASSETS.endLight, `A bead bracelet spelling “${opts.signoff}”. Thanks for visiting!`));

  return {
    markdown: out.join('\n') + '\n',
    assets: {
      [ASSETS.heroDark]: heroSvg(p, 'dark', opts),
      [ASSETS.heroLight]: heroSvg(p, 'light', opts),
      [ASSETS.diaryDark]: diarySvg(p, 'dark', opts),
      [ASSETS.diaryLight]: diarySvg(p, 'light', opts),
      [ASSETS.endDark]: braceletSvg(p, 'dark', opts),
      [ASSETS.endLight]: braceletSvg(p, 'light', opts),
    },
  };
}

export const dollhouse = {
  id: 'dollhouse',
  name: 'Dollhouse',
  tagline: 'A pastel-pink doll’s house: bubble-letter name, a cool cat in heart shades, and your year drawn as a heart of tiny hearts.',
  animated: true,
  tags: ['Animated', 'Kawaii', 'Pastel'],
  hero: (p, theme) => heroSvg(p, theme, options(p)),
  fields: [
    {
      key: 'speech',
      label: 'Speech bubble',
      help: 'What the kitten in the gift box says. Defaults to your headline.',
      maxLength: 90,
      placeholder: (p) => p.headline || 'Welcome to my dollhouse!',
    },
    {
      key: 'catName',
      label: 'Cat’s name',
      help: 'The resident cat who walks across your diary.',
      maxLength: 16,
      placeholder: (p) => defaultCatName(p),
    },
    {
      key: 'signoff',
      label: 'Bracelet beads',
      help: 'The letters on the bead bracelet at the end.',
      maxLength: 14,
      placeholder: () => 'XOXO',
    },
  ],
  render,
};
