// Ticker — the README itself. Stats Dashboard archetype (github-profile-readme skill), with every stat
// self-generated rather than hotlinked: a terminal-style hero, name and role as text, a short brief, the
// fundamentals with a plain-language key, and the watchlist of projects.

import { closingSvg, defaultSymbol, fundamentalsSvg, heroSvg, tickerNumbers } from './art';
import { renderLinks } from '../../lib/links';
import { renderSponsorWall } from '../../lib/sponsors';
import { featuredRepos, fmt, formatDate, html, languageText, picture, repoList, roleLine } from '../common';

const ASSETS = {
  heroDark: 'assets/ticker-chart-dark.svg',
  heroLight: 'assets/ticker-chart-light.svg',
  fundDark: 'assets/ticker-fundamentals-dark.svg',
  fundLight: 'assets/ticker-fundamentals-light.svg',
  endDark: 'assets/ticker-close-dark.svg',
  endLight: 'assets/ticker-close-light.svg',
};

const DEFAULT_SIGNOFF = 'Past performance does not guarantee future commits.';

function options(p) {
  const o = p.templateData?.ticker || {};
  const symbol = (o.symbol || '').toUpperCase().replace(/[^A-Z0-9.]/g, '').slice(0, 6);
  return {
    symbol: symbol || defaultSymbol(p),
    title: o.title?.trim() || '',
    organisation: o.organisation?.trim() || '',
    signoff: o.signoff?.trim() || DEFAULT_SIGNOFF,
  };
}

const heroAlt = (p, opts) => {
  const t = tickerNumbers(p);
  const role = roleLine(opts.title, opts.organisation);
  return `${p.name || p.login}${role ? `, ${role}` : ''}: ${(p.headline || 'GitHub profile').replace(/[.!?\s]+$/, '')}. Market-terminal chart under the symbol ${opts.symbol}: weekly candles of contributions in the trailing 28 days, closing at ${fmt(t.last)} (${t.change >= 0 ? 'up' : 'down'} ${fmt(Math.abs(t.change))} on the year), with a 12-month high of ${fmt(t.high)}.`;
};

const fundAlt = (p, opts) => {
  const t = tickerNumbers(p);
  return `Fundamentals for ${opts.symbol}: ${fmt(t.total)} contributions on ${fmt(t.active)} active days, best day ${t.best ? `${fmt(t.best.count)} on ${formatDate(t.best.date)}` : 'none yet'}, longest streak ${t.streak} days, ${fmt(t.stars)} stars, ${fmt(t.followers)} followers, on GitHub since ${t.since}.${
    t.languages.length ? ` Languages: ${languageText(t.languages)}.` : ''
  }`;
};

export function render(p) {
  const contact = renderLinks(p);
  const wall = renderSponsorWall(p);
  const opts = options(p);
  const name = p.name || p.login;
  const role = roleLine(opts.title, opts.organisation);
  const featured = featuredRepos(p);

  const out = [
    picture(ASSETS.heroDark, ASSETS.heroLight, heroAlt(p, opts)),
    '',
    `<p align="center"><b>${html(name)}</b>${role ? ` · ${html(role)}` : ''}${p.headline ? `<br>${html(p.headline)}` : ''}</p>`,
    contact.html,
    '',
  ];

  if (p.intro) out.push(`**Brief.** ${p.intro}`, '');
  if (p.now) out.push(`**In play:** ${p.now}`, '');

  out.push(
    '#### Fundamentals',
    '',
    picture(ASSETS.fundDark, ASSETS.fundLight, fundAlt(p, opts)),
    '',
    '<details>',
    '<summary><sub>Reading the terminal</sub></summary>',
    '',
    `- **The price** is an activity index: contributions in the trailing 28 days, read every day. The chart starts once the first 28 days are in. **${opts.symbol}** is the symbol, taken from the login unless you set one.`,
    '- **Candles** are weeks. Each shows where the index opened, closed, peaked and bottomed that week. Hollow candles closed higher than they opened; solid ones closed lower. The amber line is the four-week moving average.',
    '- **Volume** is active days per week. **12M high** and **low** are the highest and lowest the index reached this year, and the change compares the latest reading with the first.',
    '- **Fundamentals:** volume is contributions, sessions are active days, the longest rally is the longest streak, market cap is stars on public repositories, and holders are followers. **Sector allocation** is language share by bytes.',
    '- Everything is public GitHub activity from the last twelve months. None of it is investment advice.',
    '',
    '<sub>Artwork: original animated SVG, generated by README Templates · template: Ticker. Motion stops if your system asks for reduced motion.</sub>',
    '',
    '</details>',
    ''
  );

  if (featured.length) out.push('#### Watchlist', '', ...repoList(featured, (i, r) => `\`${r.name.toUpperCase().replace(/[^A-Z0-9]/g, '').slice(0, 5)}\` `), '');
  if (wall.html) out.push(wall.html, '');
  out.push(picture(ASSETS.endDark, ASSETS.endLight, `Closing bell for ${opts.symbol}. ${opts.signoff}`));

  return {
    markdown: out.join('\n') + '\n',
    assets: {
      ...contact.assets,
      ...wall.assets,
      [ASSETS.heroDark]: heroSvg(p, 'dark', opts),
      [ASSETS.heroLight]: heroSvg(p, 'light', opts),
      [ASSETS.fundDark]: fundamentalsSvg(p, 'dark', opts),
      [ASSETS.fundLight]: fundamentalsSvg(p, 'light', opts),
      [ASSETS.endDark]: closingSvg(p, 'dark', opts),
      [ASSETS.endLight]: closingSvg(p, 'light', opts),
    },
  };
}

export const ticker = {
  id: 'ticker',
  name: 'Ticker',
  tagline: 'Your year as a listed stock: weekly candlesticks drawn from your activity, a symbol from your handle, and a live tape of your repos.',
  animated: true,
  tags: ['Animated', 'Professional', 'Finance'],
  hero: (p, theme) => heroSvg(p, theme, options(p)),
  fields: [
    { key: 'symbol', label: 'Ticker symbol', help: 'Up to six letters or digits. Defaults to letters from your login.', maxLength: 6, placeholder: (p) => defaultSymbol(p) },
    { key: 'title', label: 'Title', help: 'Shown beside your name in the quote header.', maxLength: 40, placeholder: () => 'Founder & CEO' },
    { key: 'organisation', label: 'Organisation', help: 'Shown after your title.', maxLength: 40, placeholder: () => 'Company or team' },
    { key: 'signoff', label: 'Closing line', help: 'The headline of the closing bell.', maxLength: 56, placeholder: () => DEFAULT_SIGNOFF },
  ],
  sponsorPage: {
    defaults: { signoff: 'Backed by people who read the fundamentals.' },
    pitchLabel: 'The thesis.',
    nowLabel: 'In play:',
    role: (p) => roleLine(options(p).title, options(p).organisation),
    heroAlt: (p) => heroAlt(p, options(p)),
    panel: { title: 'Fundamentals', art: (p) => fundamentalsSvg(p, 'dark', options(p)), alt: (p) => fundAlt(p, options(p)) },
    fundsTitle: 'Holdings your sponsorship backs',
    repoPrefix: (i) => `\`#${i + 1}\` `,
    wall: { heading: 'On the tape', top: 'Lead backers', regular: 'Backers', oneTime: 'One-time backers' },
    outro: 'Sponsors are the long-term backers. Every one compounds.',
    end: { art: (p) => closingSvg(p, 'dark', options(p)), alt: (p) => `Closing bell for ${options(p).symbol}. ${options(p).signoff}` },
  },
  render,
};
