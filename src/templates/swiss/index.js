// Swiss — the README itself. Minimalist / Prose-First archetype (github-profile-readme skill) with a
// Visual Showcase accent: a typographic poster, then flush-left text — name, role, a short statement,
// the index with a key, and selected work as a numbered list.

import { closingSvg, heroSvg, indexSvg } from './art';
import { renderLinks } from '../../lib/links';
import { renderSponsorWall } from '../../lib/sponsors';
import { featuredRepos, fmt, html, languageText, picture, proNumbers, repoList, roleLine } from '../common';

const ASSETS = {
  heroDark: 'assets/swiss-poster-dark.svg',
  heroLight: 'assets/swiss-poster-light.svg',
  indexDark: 'assets/swiss-index-dark.svg',
  indexLight: 'assets/swiss-index-light.svg',
  endDark: 'assets/swiss-closing-dark.svg',
  endLight: 'assets/swiss-closing-light.svg',
};

const DEFAULT_SIGNOFF = 'Let’s work together.';

function options(p) {
  const o = p.templateData?.swiss || {};
  return {
    title: o.title?.trim() || '',
    organisation: o.organisation?.trim() || '',
    signoff: o.signoff?.trim() || DEFAULT_SIGNOFF,
  };
}

const heroAlt = (p, opts) => {
  const n = proNumbers(p);
  const role = roleLine(opts.title, opts.organisation);
  return `${p.name || p.login}${role ? `, ${role}` : ''}: ${(p.headline || 'GitHub profile').replace(/[.!?\s]+$/, '')}. A Swiss-style typographic poster with the name in bold on a twelve-column grid, a red disc, the figure ${fmt(n.total)} for the contributions of the last twelve months, and the year as 52 weekly bars.`;
};

const indexAlt = (p) => {
  const n = proNumbers(p);
  return `Index of the last twelve months: ${fmt(n.total)} contributions, ${fmt(n.active)} active days, longest streak ${n.streak} days, best day ${n.best?.count || 0}, ${fmt(n.stars)} stars, ${fmt(n.followers)} followers, on GitHub since ${n.since}.${
    n.languages.length ? ` Languages: ${languageText(n.languages)}.` : ''
  } Contributions per month: ${n.months.map((m) => `${m.label} ${fmt(m.total)}`).join(', ')}.`;
};

export function render(p) {
  const contact = renderLinks(p, { align: 'left' });
  const wall = renderSponsorWall(p, { align: 'left' });
  const opts = options(p);
  const name = p.name || p.login;
  const role = roleLine(opts.title, opts.organisation);
  const featured = featuredRepos(p);

  const out = [picture(ASSETS.heroDark, ASSETS.heroLight, heroAlt(p, opts)), ''];
  out.push(`**${html(name)}**${role ? `  \n${html(role)}` : ''}${p.headline ? `  \n${html(p.headline)}` : ''}`, '');
  if (contact.html) out.push(contact.html, '');
  if (p.intro) out.push(p.intro, '');
  if (p.now) out.push(`**Now.** ${p.now}`, '');

  out.push(
    '#### Index',
    '',
    picture(ASSETS.indexDark, ASSETS.indexLight, indexAlt(p)),
    '',
    '<details>',
    '<summary><sub>Key</sub></summary>',
    '',
    '- **The figure** on the poster is your contributions in the last twelve months. The bars along its foot are the 52 weeks, with the busiest in red.',
    '- **Index:** the year in numbers, language share by bytes across public repositories, and contributions per calendar month (numbered 01 to 12).',
    '',
    '<sub>Artwork: original animated SVG, generated by README Templates · template: Swiss. Motion stops if your system asks for reduced motion.</sub>',
    '',
    '</details>',
    ''
  );

  if (featured.length) out.push('#### Selected work', '', ...repoList(featured, (i) => `\`${String(i + 1).padStart(2, '0')}\` `, ' — '), '');
  if (wall.html) out.push(wall.html, '');
  out.push(picture(ASSETS.endDark, ASSETS.endLight, `${opts.signoff} ${name}${role ? `, ${role}` : ''}.`));

  return {
    markdown: out.join('\n') + '\n',
    assets: {
      ...contact.assets,
      ...wall.assets,
      [ASSETS.heroDark]: heroSvg(p, 'dark', opts),
      [ASSETS.heroLight]: heroSvg(p, 'light', opts),
      [ASSETS.indexDark]: indexSvg(p, 'dark'),
      [ASSETS.indexLight]: indexSvg(p, 'light'),
      [ASSETS.endDark]: closingSvg(p, 'dark', opts),
      [ASSETS.endLight]: closingSvg(p, 'light', opts),
    },
  };
}

export const swiss = {
  id: 'swiss',
  name: 'Swiss',
  tagline: 'An International Typographic Style poster: a strict grid, one red, flush-left type and your year as an oversized figure.',
  animated: true,
  tags: ['Animated', 'Professional', 'Typographic'],
  hero: (p, theme) => heroSvg(p, theme, options(p)),
  fields: [
    { key: 'title', label: 'Title', help: 'Set in red under your name. Defaults to the first sentence of your headline.', maxLength: 40, placeholder: () => 'Design Director' },
    { key: 'organisation', label: 'Organisation', help: 'Shown after your title.', maxLength: 40, placeholder: () => 'Studio or company' },
    { key: 'signoff', label: 'Closing line', help: 'Set large on the last card.', maxLength: 40, placeholder: () => DEFAULT_SIGNOFF },
  ],
  sponsorPage: {
    align: 'left',
    defaults: { signoff: 'Thank you for the support.' },
    pitchLabel: 'Why sponsor.',
    nowLabel: 'Now.',
    role: (p) => roleLine(options(p).title, options(p).organisation),
    heroAlt: (p) => heroAlt(p, options(p)),
    panel: { title: 'Index', art: (p) => indexSvg(p, 'dark'), alt: indexAlt },
    fundsTitle: 'Work your sponsorship supports',
    repoPrefix: (i) => `\`${String(i + 1).padStart(2, '0')}\` `,
    wall: { heading: 'Supporters', top: 'Patrons', regular: 'Supporters', oneTime: 'Friends' },
    outro: 'Good work needs time. Sponsorship buys it.',
    end: { art: (p) => closingSvg(p, 'dark', options(p)), alt: (p) => `${options(p).signoff} ${p.name || p.login}.` },
  },
  render,
};
