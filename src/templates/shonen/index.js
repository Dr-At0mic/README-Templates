// Shōnen — the README itself. Persona/Themed (anime) archetype from the github-profile-readme skill:
// hero art → plain-text identity → recap → character stat-block → projects → sign-off.
// The flash lives in the images; everything a recruiter or screen reader needs is real text.

import { characterSheetSvg, titleCardSvg, toBeContinuedSvg } from './art';
import { POWER_FORMULA, computeStats, defaultClass } from './stats';

const ASSETS = {
  titleDark: 'assets/shonen-title-dark.svg',
  titleLight: 'assets/shonen-title-light.svg',
  sheetDark: 'assets/shonen-sheet-dark.svg',
  sheetLight: 'assets/shonen-sheet-light.svg',
  endDark: 'assets/shonen-end-dark.svg',
  endLight: 'assets/shonen-end-light.svg',
};

const html = (s) => String(s ?? '').replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;').replace(/"/g, '&quot;');

function picture(dark, light, alt) {
  return [
    '<p align="center">',
    '<picture>',
    `  <source media="(prefers-color-scheme: dark)" srcset="./${dark}">`,
    `  <img alt="${html(alt)}" src="./${light}" width="100%">`,
    '</picture>',
    '</p>',
  ].join('\n');
}

function formatStars(n) {
  return n >= 1000 ? `${(n / 1000).toFixed(n >= 10000 ? 0 : 1)}k` : String(n);
}

function links(p) {
  const twitter = p.twitter?.replace(/^@/, '');
  const items = [
    p.website && `<a href="${html(p.website)}">${html(p.website.replace(/^https?:\/\//, '').replace(/\/$/, ''))}</a>`,
    p.email && `<a href="mailto:${html(p.email)}">${html(p.email)}</a>`,
    twitter && `<a href="https://x.com/${html(twitter)}">X @${html(twitter)}</a>`,
    p.linkedin && `<a href="${html(p.linkedin)}">LinkedIn</a>`,
  ].filter(Boolean);
  return items.length ? `<p align="center">${items.join(' &nbsp;·&nbsp; ')}</p>` : '';
}

export function render(p) {
  const opts = p.templateData?.shonen || {};
  const catchphrase = opts.catchphrase?.trim() || p.headline || 'A new challenger approaches!';
  const heroClass = opts.heroClass?.trim() || defaultClass(p);
  const name = p.name || p.login;
  const { stats, rank, power, over9000 } = computeStats(p);
  const featured = p.featured.map((n) => p.repos.find((r) => r.name === n)).filter(Boolean);

  const out = [];
  out.push(
    picture(ASSETS.titleDark, ASSETS.titleLight, `Anime title card: ${name}. Speech bubble: “${catchphrase}”`),
    '',
    `<p align="center"><b>${html(name)}</b>${p.headline ? ` — ${html(p.headline)}` : ''}</p>`,
    links(p),
    ''
  );

  if (p.intro) out.push(`**Previously on @${p.login}…** ${p.intro}`, '');
  if (p.now) out.push(`**Next episode:** ${p.now}`, '');

  out.push(
    '#### Character sheet',
    '',
    picture(
      ASSETS.sheetDark,
      ASSETS.sheetLight,
      `Character sheet. Class: ${heroClass}. Rank ${rank}. Power level ${power.toLocaleString('en-US')}${over9000 ? ' — it’s over 9000' : ''}. ` +
        stats.map((s) => `${s.key} (${s.label}): ${s.value.toLocaleString('en-US')}`).join('; ') +
        '.'
    ),
    '',
    '<details>',
    '<summary><sub>How these stats are computed</sub></summary>',
    '',
    ...stats.map((s) => `- **${s.key}** — ${s.label}: ${s.value.toLocaleString('en-US')}`),
    `- **Rank** — average of the five bars (S ≥ 85%, A ≥ 70%, B ≥ 50%, C ≥ 30%).`,
    `- **Power level** — ${POWER_FORMULA}. Scientifically meaningless. Spiritually accurate.`,
    '',
    '<sub>Artwork: original animated SVG, generated by README Templates · template: Shōnen. Motion stops if your system asks for reduced motion.</sub>',
    '',
    '</details>',
    ''
  );

  if (featured.length) {
    out.push('#### Story arcs', '');
    featured.forEach((repo, i) => {
      out.push(`- **Arc ${i + 1} · [${repo.name}](${repo.url})**${repo.description ? ` — ${repo.description}` : ''}  `);
      const meta = [repo.language, repo.stars ? `★ ${formatStars(repo.stars)}` : ''].filter(Boolean).join(' · ');
      if (meta) out.push(`  <sub>${meta}</sub>`);
    });
    out.push('');
  }

  out.push(picture(ASSETS.endDark, ASSETS.endLight, 'To be continued…'));

  const markdown = out.filter((line, i, arr) => !(line === '' && arr[i - 1] === '')).join('\n') + '\n';
  const assets = {
    [ASSETS.titleDark]: titleCardSvg(p, 'dark', { catchphrase }),
    [ASSETS.titleLight]: titleCardSvg(p, 'light', { catchphrase }),
    [ASSETS.sheetDark]: characterSheetSvg(p, 'dark', { heroClass }),
    [ASSETS.sheetLight]: characterSheetSvg(p, 'light', { heroClass }),
    [ASSETS.endDark]: toBeContinuedSvg(p, 'dark'),
    [ASSETS.endLight]: toBeContinuedSvg(p, 'light'),
  };
  return { markdown, assets };
}

export const shonen = {
  id: 'shonen',
  name: 'Shōnen',
  tagline: 'Your profile as an anime opening — speed lines, a title card, and a power level that’s wildly over 9000.',
  animated: true,
  tags: ['Animated', 'Anime', 'Playful'],
  hero: (p, theme) =>
    titleCardSvg(p, theme, {
      catchphrase: p.templateData?.shonen?.catchphrase?.trim() || p.headline || 'A new challenger approaches!',
    }),
  fields: [
    {
      key: 'catchphrase',
      label: 'Catchphrase',
      help: 'Shouted in the speech bubble. Defaults to your headline.',
      maxLength: 90,
      placeholder: (p) => p.headline || 'A new challenger approaches!',
    },
    {
      key: 'heroClass',
      label: 'Class',
      help: 'Your character class on the sheet. Defaults from your top language.',
      maxLength: 32,
      placeholder: (p) => defaultClass(p),
    },
  ],
  render,
};
